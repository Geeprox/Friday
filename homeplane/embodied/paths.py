"""Friday-owned local storage. Importing this module never opens a camera."""

from __future__ import annotations

import json
import os
from pathlib import Path

SOURCE = Path(__file__).resolve().parent
PROJECT = SOURCE.parents[1]
DATA = Path(os.environ.get("FRIDAY_EMBODIED_DATA", PROJECT / "data/embodied")).absolute()
PRIVATE = DATA / "private"
MODELS = DATA / "models"
PYTHON = DATA / "runtime/bin/python"
VISION = DATA / "bin/friday-vision"
SOCKETS = DATA / "bin/camera-sockets.dylib"


def capture_environment():
    import re

    environment = dict(os.environ)
    interface = configuration().get("camera_interface")
    if interface:
        if not re.fullmatch(r"en[0-9]{1,2}", interface) or not SOCKETS.is_file():
            raise ValueError("camera_interface_unavailable")
        environment["FRIDAY_CAMERA_INTERFACE"] = interface
        # Only supplied to the isolated Miloco SDK subprocess, never Console,
        # games, models or the system. No shell/global environment is modified.
        environment["DYLD_INSERT_LIBRARIES"] = str(SOCKETS)
    return environment


def configuration():
    path = PRIVATE / "config.json"
    if path.is_symlink() or path.stat().st_mode & 0o077:
        raise ValueError("invalid_config")
    value = json.loads(path.read_text())
    if value.get("version") != 1 or not 1 <= len(value.get("cameras", [])) <= 8:
        raise ValueError("invalid_config")
    return value


def camera(camera_id=None):
    config = configuration()
    selected = camera_id or os.environ.get("FRIDAY_CAMERA_ID") or config["default_camera"]
    matches = [c for c in config["cameras"] if c["id"] == selected]
    if len(matches) != 1:
        raise ValueError("camera_not_registered")
    return matches[0]


def camera_storage(camera_id=None):
    selected = camera(camera_id)
    # IDs are generated by provisioning, never accepted as filesystem components.
    import re

    if not re.fullmatch(r"cam_[a-f0-9]{10}", selected["id"]):
        raise ValueError("invalid_config")
    folder = PRIVATE / "cameras" / selected["id"]
    folder.mkdir(parents=True, exist_ok=True, mode=0o700)
    return folder
